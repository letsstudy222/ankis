"use strict";
const assert = require('node:assert/strict');
require('../guardian-model.js');
require('../guardian-nursery.js');
const M = GuardianModel, N = GuardianNursery;
const fresh = tickets => { const s = M.create(); N.ensure(s).tickets = tickets; return s; };
let s = fresh(99);
const before = JSON.stringify(s);
assert.equal(N.summonMany(s, 10).ok, false);
assert.equal(JSON.stringify(s), before, 'insufficient tickets must not partially draw');
s = fresh(100);
s.nursery.pity = 49;
s.nursery.pulls = 49;
const draws = N.summonMany(s, 10, () => 0);
assert.equal(draws.results.length, 10);
assert.equal(s.nursery.tickets, 0);
assert.equal(s.nursery.pulls, 59);
assert.equal(draws.results[0].rarity, 'rainbow');
assert.equal(draws.results[0].guaranteed, true);
assert.equal(s.nursery.pity, 9);
assert.equal(s.nursery.history.length, 10);
assert.equal(s.nursery.pets.fox.copies, 10);
assert.equal(s.nursery.pets.fox.xp, 9 * N.tiers.normal.duplicateXP);
assert.equal(N.valid(s), true);
const restored = JSON.parse(JSON.stringify(s));
assert.deepEqual(N.ensure(restored).history, s.nursery.history);
assert.equal(N.summonMany(restored, 1).ok, false);
console.log('PASS: x10 ticket precheck, exact cost, sequential hard pity/reset, duplicate XP, history and save roundtrip.');
